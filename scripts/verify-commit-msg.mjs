#!/usr/bin/env node
// Validates a commit message against the DocStruct commit convention
// (Conventional Commits 1.0.0 with a fixed scope list). See docs/GIT_WORKFLOW.md.
//
// Usage:
//   node scripts/verify-commit-msg.mjs <path-to-COMMIT_EDITMSG>   (git hook)
//   node scripts/verify-commit-msg.mjs --message "feat(auth): add login"
//   node scripts/verify-commit-msg.mjs --range main..develop      (CI: check a range)
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

export const TYPES = ['feat', 'fix', 'docs', 'style', 'refactor', 'perf', 'test', 'build', 'ci', 'chore', 'revert'];

export const SCOPES = [
  // modules (see docs/TEAM.md)
  'auth', 'project', 'document', 'folder', 'version', 'review', 'rbac',
  'annotation', 'share', 'search', 'activity', 'dashboard', 'diff', 'extractor',
  // layers / cross-cutting
  'api', 'web', 'shared', 'db', 'storage', 'ci', 'docs', 'repo', 'deps', 'release',
];

const HEADER = /^(?<type>[a-z]+)(?:\((?<scope>[a-z0-9-]+)\))?(?<breaking>!)?: (?<subject>.+)$/;

/** Returns a list of problems; an empty list means the message is valid. */
export function validate(message) {
  const lines = message.replace(/\r\n/g, '\n').split('\n').filter((l) => !l.startsWith('#'));
  const header = lines[0] ?? '';

  // Merge, revert and fixup commits generated by git are accepted as-is.
  if (/^(Merge|Revert|fixup!|squash!) /.test(header)) return [];

  const problems = [];
  const match = HEADER.exec(header);
  if (!match) {
    return [`header must look like "type(scope): subject" - got "${header}"`];
  }
  const { type, scope, subject } = match.groups;
  if (!TYPES.includes(type)) problems.push(`unknown type "${type}" (allowed: ${TYPES.join(', ')})`);
  if (scope && !SCOPES.includes(scope)) problems.push(`unknown scope "${scope}" (allowed: ${SCOPES.join(', ')})`);
  if (header.length > 72) problems.push(`header is ${header.length} characters; keep it to 72`);
  if (/^[A-Z]/.test(subject)) problems.push('subject must start with a lower-case letter');
  if (/\.$/.test(subject)) problems.push('subject must not end with a full stop');
  if (lines.length > 1 && lines[1].trim() !== '') problems.push('leave a blank line between the header and the body');
  return problems;
}

function main(argv) {
  let messages = [];
  if (argv[0] === '--message') {
    messages = [{ ref: 'message', text: argv[1] ?? '' }];
  } else if (argv[0] === '--range') {
    const out = execFileSync('git', ['log', '--format=%H%x00%B%x01', argv[1]], { encoding: 'utf8' });
    messages = out.split('\x01').map((s) => s.trim()).filter(Boolean).map((entry) => {
      const [hash, text] = entry.split('\x00');
      return { ref: hash.slice(0, 8), text };
    });
  } else if (argv[0]) {
    messages = [{ ref: 'commit', text: readFileSync(argv[0], 'utf8') }];
  } else {
    console.error('usage: verify-commit-msg.mjs <file> | --message <text> | --range <a..b>');
    process.exit(2);
  }

  let failed = false;
  for (const { ref, text } of messages) {
    const problems = validate(text);
    if (problems.length) {
      failed = true;
      console.error(`✖ ${ref}: ${text.split('\n')[0]}`);
      for (const p of problems) console.error(`    - ${p}`);
    }
  }
  if (failed) {
    console.error('\nSee docs/GIT_WORKFLOW.md#commit-message-convention');
    process.exit(1);
  }
}

if (process.argv[1]?.endsWith('verify-commit-msg.mjs')) {
  main(process.argv.slice(2));
}
